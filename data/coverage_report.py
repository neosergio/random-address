"""Write COVERAGE.md, the per-state account of what the dataset holds.

This is a maintainer tool, not part of the published package. COVERAGE.md is
generated from the dataset rather than written by hand, and tests/test_coverage.py
fails when the two disagree, so the page can never describe an older dataset.

    python data/coverage_report.py           # rewrite COVERAGE.md
    python data/coverage_report.py --check   # exit 1 if COVERAGE.md is stale
"""

