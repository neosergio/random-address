def render(addresses: list[dict[str, Any]]) -> str:
    """Return the full text of COVERAGE.md for the given addresses."""
    totals: dict[str, int] = defaultdict(int)
    cities: dict[str, set[str]] = defaultdict(set)
    postal_codes: dict[str, set[str]] = defaultdict(set)
    for address in addresses:
        state = address["state"]
        totals[state] += 1
        cities[state].add(address["city"].casefold())
        postal_codes[state].add(address["postal_code"])

    every_postal_code = {address["postal_code"] for address in addresses}
    missing = [code for code in sorted(STATE_NAMES) if code not in totals]

    lines = [
        "# Dataset coverage",
        "",
        "<!-- Generated by data/coverage_report.py. Do not edit by hand: run",
        "     `python data/coverage_report.py` after changing the dataset. -->",
        "",
        "What the bundled dataset holds, per state. Every address is public domain; see",
        "Attribution in the README for the sources.",
        "",
        f"- **{len(addresses):,}** addresses",
        f"- **{len(totals)}** of {len(STATE_NAMES)} states (DC counted as a state)",
        f"- **{len(every_postal_code):,}** postal codes",
        "",
        "| State | Name | Addresses | Cities | Postal codes |",
        "| --- | --- | ---: | ---: | ---: |",
    ]
    for state in sorted(totals):
        lines.append(
            f"| {state} | {STATE_NAMES.get(state, '?')} | {totals[state]:,} "
            f"| {len(cities[state])} | {len(postal_codes[state])} |"
        )

    lines += ["", "## Not yet covered", ""]
    if missing:
        lines += [
            ", ".join(missing),
            "",
            "Coverage is gated on licensing, not effort: a state is added once a public",
            "domain source for it has been found. ROADMAP.md records why the obvious",
            "candidates have not qualified. To ask for a place, open a GitHub issue.",
        ]
    else:
        lines.append("Every state is represented.")
    return "\n".join(lines) + "\n"


def _read_dataset() -> list[dict[str, Any]]:
    with DATASET.open(encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Report whether COVERAGE.md is current, without writing it.",
    )
    args = parser.parse_args(argv)

    expected = render(_read_dataset())
    if args.check:
        current = COVERAGE.read_text(encoding="utf-8") if COVERAGE.exists() else ""
        if current != expected:
            print("COVERAGE.md is stale. Run: python data/coverage_report.py", file=sys.stderr)
            return 1
        print("COVERAGE.md is current.")
        return 0

    COVERAGE.write_text(expected, encoding="utf-8")
    print(f"Wrote {COVERAGE.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
